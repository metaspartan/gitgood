import { createHash } from "node:crypto";
import { all, changes, now, one, run, scalar } from "../db/index.ts";
import { conflict, unprocessable } from "../lib/errors.ts";

export interface SshKeyRow {
  id: number;
  user_id: number;
  title: string;
  fingerprint: string;
  public_key: string;
  created_at: number;
}

export interface ParsedKey {
  algorithm: string;
  blob: string;
  comment: string;
  fingerprint: string;
  normalized: string;
}

const SUPPORTED_ALGORITHMS = new Set([
  "ssh-ed25519",
  "ssh-rsa",
  "ecdsa-sha2-nistp256",
  "ecdsa-sha2-nistp384",
  "ecdsa-sha2-nistp521",
  "sk-ssh-ed25519@openssh.com",
  "sk-ecdsa-sha2-nistp256@openssh.com",
]);

export function fingerprintOf(blobBase64: string): string {
  const digest = createHash("sha256").update(Buffer.from(blobBase64, "base64")).digest("base64");
  return `SHA256:${digest.replace(/=+$/, "")}`;
}

export function parsePublicKey(input: string): ParsedKey | null {
  const line = input.trim().split(/\r?\n/).find((candidate) => {
    const trimmed = candidate.trim();
    return trimmed.length > 0 && !trimmed.startsWith("#");
  });
  if (!line) return null;

  const parts = line.trim().split(/\s+/);
  if (parts.length < 2) return null;
  const [algorithm, blob, ...rest] = parts;
  if (!algorithm || !blob) return null;
  if (!SUPPORTED_ALGORITHMS.has(algorithm)) return null;

  if (!/^[A-Za-z0-9+/]+={0,3}$/.test(blob)) return null;
  const decoded = Buffer.from(blob, "base64");
  if (decoded.length === 0) return null;
  const nameLength = decoded.readUInt32BE(0);
  if (nameLength <= 0 || nameLength > 64 || 4 + nameLength > decoded.length) return null;
  const embedded = decoded.subarray(4, 4 + nameLength).toString("ascii");
  if (embedded !== algorithm) return null;

  return {
    algorithm,
    blob,
    comment: rest.join(" ").trim(),
    fingerprint: fingerprintOf(blob),
    normalized: rest.length > 0 ? `${algorithm} ${blob} ${rest.join(" ")}` : `${algorithm} ${blob}`,
  };
}

export interface AddKeyInput {
  title?: string;
  publicKey: string;
}

export function listKeys(userId: number): SshKeyRow[] {
  return all<SshKeyRow>(
    "SELECT * FROM ssh_keys WHERE user_id = ? ORDER BY id DESC",
    userId,
  );
}

export function findKeyByFingerprint(fingerprint: string): SshKeyRow | null {
  return one<SshKeyRow>("SELECT * FROM ssh_keys WHERE fingerprint = ?", fingerprint);
}

export function addKey(userId: number, input: AddKeyInput): SshKeyRow {
  const parsed = parsePublicKey(input.publicKey);
  if (!parsed) {
    throw unprocessable(
      "That does not look like a supported public key. Paste a line from an SSH public key file.",
    );
  }

  const existing = findKeyByFingerprint(parsed.fingerprint);
  if (existing) {
    if (existing.user_id === userId) throw conflict("That key is already on your account");
    throw conflict("That key is already registered to another account");
  }

  const count = scalar<number>("SELECT COUNT(*) FROM ssh_keys WHERE user_id = ?", userId) ?? 0;
  if (count >= 50) throw conflict("You have reached the limit of 50 SSH keys");

  const title = input.title?.trim() || parsed.comment || `${parsed.algorithm} key`;
  const id = run(
    "INSERT INTO ssh_keys (user_id, title, fingerprint, public_key, created_at) VALUES (?, ?, ?, ?, ?)",
    userId,
    title.slice(0, 120),
    parsed.fingerprint,
    parsed.normalized,
    now(),
  );
  const created = one<SshKeyRow>("SELECT * FROM ssh_keys WHERE id = ?", id);
  if (!created) throw unprocessable("Failed to store the key");
  return created;
}

export function removeKey(userId: number, id: number): boolean {
  return changes("DELETE FROM ssh_keys WHERE id = ? AND user_id = ?", id, userId) > 0;
}

export function authorizedKeysLine(key: SshKeyRow, sshCommand: string): string {
  const command = sshCommand.trim() || "/usr/local/bin/gitgood-ssh-command";
  const options = [
    `command="${command.replace(/"/g, '\\"')}"`,
    `environment="GITGOOD_SSH_FINGERPRINT=${key.fingerprint}"`,
    "restrict",
    "no-port-forwarding",
    "no-X11-forwarding",
    "no-agent-forwarding",
    "no-pty",
    "no-user-rc",
  ];
  return `${options.join(",")} ${key.public_key}`;
}

export function authorizedKeysFile(keys: SshKeyRow[], sshCommand: string): string {
  const header = [
    "# Generated by `bun tools/ssh-authorized-keys.ts`. Do not edit by hand.",
    "#",
    "# Every key is a forced command: it may run the git command and nothing else.",
    "# Regenerate after adding or removing a key in the web UI.",
    "",
  ].join("\n");
  const lines = keys.map((key) => authorizedKeysLine(key, sshCommand));
  return `${header}${lines.join("\n")}\n`;
}

export function listAllKeysWithOwners(): Array<SshKeyRow & { username: string }> {
  return all<SshKeyRow & { username: string }>(
    `SELECT k.*, u.username
       FROM ssh_keys k JOIN users u ON u.id = k.user_id
      WHERE u.blocked_at IS NULL
      ORDER BY u.username, k.id`,
  );
}
